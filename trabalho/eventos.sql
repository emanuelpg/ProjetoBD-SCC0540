-- Tipos auxiliares (DOMAIN / ENUM) e tabelas.
-- Executar conectado ao banco "eventos":
--   psql -U postgres -d eventos -f 01_ddl_tabelas.sql
--
-- O script roda dentro de uma transacao: ou cria tudo, ou nada.
-- Pode ser executado varias vezes (remove e recria os objetos).
