BEGIN;

-- ------------------------------------------------------------
-- 0. Limpeza (permite reexecutar o script)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS inscricao        CASCADE;
DROP TABLE IF EXISTS credenciamento   CASCADE;
DROP TABLE IF EXISTS participante     CASCADE;
DROP TABLE IF EXISTS recursos_sessao  CASCADE;
DROP TABLE IF EXISTS estoque          CASCADE;
DROP TABLE IF EXISTS recursos         CASCADE;
DROP TABLE IF EXISTS sessao           CASCADE;
DROP TABLE IF EXISTS espaco           CASCADE;
DROP TABLE IF EXISTS atividade        CASCADE;
DROP TABLE IF EXISTS patrocinio       CASCADE;
DROP TABLE IF EXISTS organizacao      CASCADE;
DROP TABLE IF EXISTS pessoa_promotor  CASCADE;
DROP TABLE IF EXISTS promotor         CASCADE;
DROP TABLE IF EXISTS evento           CASCADE;

DROP TYPE   IF EXISTS papel_inscricao CASCADE;
DROP DOMAIN IF EXISTS dom_cpf         CASCADE;
DROP DOMAIN IF EXISTS dom_cnpj        CASCADE;
DROP DOMAIN IF EXISTS dom_cep         CASCADE;
DROP DOMAIN IF EXISTS dom_email       CASCADE;
DROP DOMAIN IF EXISTS dom_telefone    CASCADE;
DROP DOMAIN IF EXISTS dom_uf          CASCADE;
DROP DOMAIN IF EXISTS dom_dinheiro    CASCADE;

-- ------------------------------------------------------------
-- 1. Dominios (tipos com regra de validacao reaproveitavel)
-- ------------------------------------------------------------

-- CPF: 11 digitos, somente numeros (sem pontos e traco)
CREATE DOMAIN dom_cpf AS CHAR(11)
    CHECK (VALUE ~ '^[0-9]{11}$');

-- CNPJ: 14 digitos, somente numeros
CREATE DOMAIN dom_cnpj AS CHAR(14)
    CHECK (VALUE ~ '^[0-9]{14}$');

-- CEP: 8 digitos, somente numeros
CREATE DOMAIN dom_cep AS CHAR(8)
    CHECK (VALUE ~ '^[0-9]{8}$');

-- E-mail: formato basico texto@texto.texto
CREATE DOMAIN dom_email AS VARCHAR(120)
    CHECK (VALUE ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$');

-- Telefone: DDD + numero, 10 ou 11 digitos
CREATE DOMAIN dom_telefone AS VARCHAR(11)
    CHECK (VALUE ~ '^[0-9]{10,11}$');

-- Unidade federativa
CREATE DOMAIN dom_uf AS CHAR(2)
    CHECK (VALUE IN ('AC','AL','AP','AM','BA','CE','DF','ES','GO','MA',
                     'MT','MS','MG','PA','PB','PR','PE','PI','RJ','RN',
                     'RS','RO','RR','SC','SP','SE','TO'));

-- Valores monetarios nao negativos
CREATE DOMAIN dom_dinheiro AS NUMERIC(12,2)
    CHECK (VALUE >= 0);

-- ------------------------------------------------------------
-- 2. Enum
-- ------------------------------------------------------------

-- Papel exercido por um participante credenciado em uma sessao
CREATE TYPE papel_inscricao AS ENUM ('ouvinte', 'instrutor', 'palestrante');

-- ------------------------------------------------------------
-- 3. Tabelas
--    Ordem: primeiro as tabelas referenciadas, depois as que
--    possuem chave estrangeira para elas.
-- ------------------------------------------------------------

-- EVENTO -----------------------------------------------------
CREATE TABLE evento (
    EventoId   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    Nome       VARCHAR(150) NOT NULL,
    Inicio     TIMESTAMP    NOT NULL,
    Fim        TIMESTAMP    NOT NULL,
    Descricao  TEXT,

    CONSTRAINT pk_evento PRIMARY KEY (EventoId),
    CONSTRAINT ck_evento_periodo CHECK (Fim > Inicio)
);

-- PROMOTOR (entidade generica da especializacao disjunta) -----
CREATE TABLE promotor (
    PromotorId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    Email      dom_email,
    Telefone   dom_telefone,
    Nome       VARCHAR(150) NOT NULL,
    CEP        dom_cep,
    Endereco   VARCHAR(200),

    CONSTRAINT pk_promotor          PRIMARY KEY (PromotorId),
    CONSTRAINT uq_promotor_email    UNIQUE (Email),
    CONSTRAINT uq_promotor_telefone UNIQUE (Telefone)
);

-- PESSOA_PROMOTOR (subtipo: pessoa fisica) --------------------
-- A PK e tambem FK para promotor (heranca da chave).
CREATE TABLE pessoa_promotor (
    PessoaPId  INTEGER  NOT NULL,
    CPF        dom_cpf  NOT NULL,

    CONSTRAINT pk_pessoa_promotor     PRIMARY KEY (PessoaPId),
    CONSTRAINT uq_pessoa_promotor_cpf UNIQUE (CPF),
    CONSTRAINT fk_pessoa_promotor_promotor
        FOREIGN KEY (PessoaPId) REFERENCES promotor (PromotorId)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- ORGANIZACAO (subtipo: pessoa juridica) ----------------------
CREATE TABLE organizacao (
    OrganizacaoId INTEGER  NOT NULL,
    CNPJ          dom_cnpj NOT NULL,

    CONSTRAINT pk_organizacao      PRIMARY KEY (OrganizacaoId),
    CONSTRAINT uq_organizacao_cnpj UNIQUE (CNPJ),
    CONSTRAINT fk_organizacao_promotor
        FOREIGN KEY (OrganizacaoId) REFERENCES promotor (PromotorId)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- PATROCINIO (Evento M:N Promotor) ----------------------------
CREATE TABLE patrocinio (
    EventoId        INTEGER      NOT NULL,
    PromotorId      INTEGER      NOT NULL,
    Valor           dom_dinheiro NOT NULL,
    Data_patrocinio DATE         NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_patrocinio PRIMARY KEY (EventoId, PromotorId),
    CONSTRAINT fk_patrocinio_evento
        FOREIGN KEY (EventoId) REFERENCES evento (EventoId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_patrocinio_promotor
        FOREIGN KEY (PromotorId) REFERENCES promotor (PromotorId)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ATIVIDADE (Evento 1:N Atividade, participacao total) --------
CREATE TABLE atividade (
    AtividadeId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EventoId    INTEGER      NOT NULL,
    Nome        VARCHAR(150) NOT NULL,
    Descricao   TEXT,

    CONSTRAINT pk_atividade PRIMARY KEY (AtividadeId),
    CONSTRAINT fk_atividade_evento
        FOREIGN KEY (EventoId) REFERENCES evento (EventoId)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- ESPACO -----------------------------------------------------
CREATE TABLE espaco (
    EspacoId      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    Nome          VARCHAR(100) NOT NULL,
    LimitePessoas INTEGER      NOT NULL,
    CEP           dom_cep      NOT NULL,
    Numero        VARCHAR(10)  NOT NULL,
    Rua           VARCHAR(150),
    Bairro        VARCHAR(100),
    Cidade        VARCHAR(100),
    Estado        dom_uf,

    CONSTRAINT pk_espaco PRIMARY KEY (EspacoId),
    CONSTRAINT ck_espaco_limite CHECK (LimitePessoas > 0)
);

-- SESSAO (Atividade 1:N Sessao, participacao total;
--         Sessao N:1 Espaco, participacao parcial) -----------
CREATE TABLE sessao (
    SessaoId       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    AtividadeId    INTEGER      NOT NULL,
    EspacoId       INTEGER,                    -- pode ficar sem espaco definido
    Nome           VARCHAR(150) NOT NULL,
    DataHoraInicio TIMESTAMP    NOT NULL,
    Duracao        INTEGER      NOT NULL,      -- em minutos
    Vagas          INTEGER      NOT NULL,
    Valor          dom_dinheiro NOT NULL DEFAULT 0,

    -- Atributo gerado: termino da sessao, calculado a partir do inicio
    -- e da duracao. Facilita a verificacao de conflito de horario.
    DataHoraFim    TIMESTAMP GENERATED ALWAYS AS
                   (DataHoraInicio + make_interval(mins => Duracao)) STORED,

    CONSTRAINT pk_sessao PRIMARY KEY (SessaoId),
    CONSTRAINT ck_sessao_duracao CHECK (Duracao > 0),
    CONSTRAINT ck_sessao_vagas   CHECK (Vagas > 0),
    CONSTRAINT fk_sessao_atividade
        FOREIGN KEY (AtividadeId) REFERENCES atividade (AtividadeId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_sessao_espaco
        FOREIGN KEY (EspacoId) REFERENCES espaco (EspacoId)
        ON DELETE SET NULL ON UPDATE CASCADE
);

-- RECURSOS ---------------------------------------------------
CREATE TABLE recursos (
    RecursoId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    Nome      VARCHAR(100) NOT NULL,
    Descricao TEXT         NOT NULL,

    CONSTRAINT pk_recursos      PRIMARY KEY (RecursoId),
    CONSTRAINT uq_recursos_nome UNIQUE (Nome)
);

-- ESTOQUE (Espaco M:N Recursos) ------------------------------
CREATE TABLE estoque (
    EstoqueId  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EspacoId   INTEGER NOT NULL,
    RecursoId  INTEGER NOT NULL,
    Quantidade INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT pk_estoque PRIMARY KEY (EstoqueId),
    CONSTRAINT uq_estoque_espaco_recurso UNIQUE (EspacoId, RecursoId),
    CONSTRAINT ck_estoque_quantidade CHECK (Quantidade > 0),
    CONSTRAINT fk_estoque_espaco
        FOREIGN KEY (EspacoId) REFERENCES espaco (EspacoId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_estoque_recurso
        FOREIGN KEY (RecursoId) REFERENCES recursos (RecursoId)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- RECURSOS_SESSAO (Sessao M:N Recursos) ----------------------
CREATE TABLE recursos_sessao (
    RecursoSessaoId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    SessaoId        INTEGER NOT NULL,
    RecursoId       INTEGER NOT NULL,
    QtdNecessaria   INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT pk_recursos_sessao PRIMARY KEY (RecursoSessaoId),
    CONSTRAINT uq_recursos_sessao_sessao_recurso UNIQUE (SessaoId, RecursoId),
    CONSTRAINT ck_recursos_sessao_qtd CHECK (QtdNecessaria > 0),
    CONSTRAINT fk_recursos_sessao_sessao
        FOREIGN KEY (SessaoId) REFERENCES sessao (SessaoId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_recursos_sessao_recurso
        FOREIGN KEY (RecursoId) REFERENCES recursos (RecursoId)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- PARTICIPANTE -----------------------------------------------
CREATE TABLE participante (
    ParticipanteId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CPF            dom_cpf      NOT NULL,
    Nome           VARCHAR(150) NOT NULL,
    DataNascimento DATE         NOT NULL,

    CONSTRAINT pk_participante     PRIMARY KEY (ParticipanteId),
    CONSTRAINT uq_participante_cpf UNIQUE (CPF),
    CONSTRAINT ck_participante_nascimento CHECK (DataNascimento > DATE '1900-01-01')
);

-- CREDENCIAMENTO (Participante M:N Evento - agregacao) --------
-- Organizacao = TRUE indica que o participante e organizador do evento.
CREATE TABLE credenciamento (
    CredenciamentoId INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ParticipanteId   INTEGER NOT NULL,
    EventoId         INTEGER NOT NULL,
    Organizacao      BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_credenciamento PRIMARY KEY (CredenciamentoId),
    CONSTRAINT uq_credenciamento_participante_evento UNIQUE (ParticipanteId, EventoId),
    CONSTRAINT fk_credenciamento_participante
        FOREIGN KEY (ParticipanteId) REFERENCES participante (ParticipanteId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_credenciamento_evento
        FOREIGN KEY (EventoId) REFERENCES evento (EventoId)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- INSCRICAO (Credenciamento M:N Sessao) ----------------------
CREATE TABLE inscricao (
    InscricaoId      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CredenciamentoId INTEGER         NOT NULL,
    SessaoId         INTEGER         NOT NULL,
    DataHora         TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Papel            papel_inscricao NOT NULL DEFAULT 'ouvinte',

    CONSTRAINT pk_inscricao PRIMARY KEY (InscricaoId),
    CONSTRAINT uq_inscricao_credenciamento_sessao UNIQUE (CredenciamentoId, SessaoId),
    CONSTRAINT fk_inscricao_credenciamento
        FOREIGN KEY (CredenciamentoId) REFERENCES credenciamento (CredenciamentoId)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_inscricao_sessao
        FOREIGN KEY (SessaoId) REFERENCES sessao (SessaoId)
        ON DELETE CASCADE ON UPDATE CASCADE
);

COMMIT;